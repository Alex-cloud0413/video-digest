  function normalizeLanguage(value) {
    return SUPPORTED_LANGUAGES.includes(value) ? value : "en";
  }

  function translate(language, key, variables = {}) {
    const normalized = normalizeLanguage(language);
    const template = COPY[normalized]?.[key] ?? COPY.en[key] ?? key;
    return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (_match, name) =>
      Object.prototype.hasOwnProperty.call(variables, name)
        ? String(variables[name])
        : `{${name}}`,
    );
  }

  function applyDocument(language, documentRef) {
    const normalized = normalizeLanguage(language);
    if (!documentRef) return normalized;
    documentRef.documentElement.lang = normalized;
    documentRef.title = translate(normalized, "pageTitle");
    documentRef.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = translate(normalized, element.dataset.i18n);
    });
    for (const [attribute, dataName] of [
      ["title", "i18nTitle"],
      ["aria-label", "i18nAriaLabel"],
      ["placeholder", "i18nPlaceholder"],
    ]) {
      documentRef.querySelectorAll(`[data-${dataName.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}]`).forEach((element) => {
        element.setAttribute(attribute, translate(normalized, element.dataset[dataName]));
      });
    }
    return normalized;
  }

  return {
    COPY,
    LANGUAGE_BADGES,
    STORAGE_KEY,
    SUPPORTED_LANGUAGES,
    applyDocument,
    normalizeLanguage,
    translate,
  };
